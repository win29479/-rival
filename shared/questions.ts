/**
 * Picks an unanswered question for a player so they can NEVER farm points
 * by repeating the same question. Respects preferredDifficulty when available.
 */
export function pickNextQuestion(
  usedIds: ReadonlySet<string>,
  preferredDifficulty?: Difficulty,
  rng: () => number = Math.random,
): MathQuestion | null {
  let candidates = QUESTION_BANK.filter((q) => !usedIds.has(q.id))
  if (candidates.length === 0) {
    return null
  }
  if (preferredDifficulty) {
    const filtered = candidates.filter((q) => q.difficulty === preferredDifficulty)
    if (filtered.length > 0) {
      candidates = filtered
    }
  }
  const idx = Math.floor(rng() * candidates.length)
  return candidates[idx]
}
